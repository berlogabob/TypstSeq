import 'package:test/test.dart';
import 'package:tylog_core/tylog_core.dart';

void main() {
  test('parses explicit loan dates', () {
    final cases = <(String, String, String?)>[
      ('until Friday', '2026-11-12', '2026-11-13'),
      ('TILL MON', '2026-11-12', '2026-11-16'),
      ('by Thursday', '2026-11-12', '2026-11-19'),
      ('by tomorrow', '2026-11-12', '2026-11-13'),
      ('until tomorrow', '2026-11-12', '2026-11-13'),
      ('till tomorrow', '2026-11-12', '2026-11-13'),
      ('until 20 Nov', '2026-11-12', '2026-11-20'),
      ('till 20th November', '2026-11-12', '2026-11-20'),
      ('by November 20th', '2026-11-12', '2026-11-20'),
      ('by Nov 20', '2026-11-12', '2026-11-20'),
      ('until 20 Jan', '2026-12-28', '2027-01-20'),
      ('for 2 days', '2026-11-12', '2026-11-14'),
      ('for 1 day', '2026-11-12', '2026-11-13'),
      ('for a day', '2026-11-12', '2026-11-13'),
      ('for one day', '2026-11-12', '2026-11-13'),
      ('for a week', '2026-11-12', '2026-11-19'),
      ('for 2 weeks', '2026-11-12', '2026-11-26'),
      ('for 1 week', '2026-11-12', '2026-11-19'),
      ('até segunda-feira', '2026-11-12', '2026-11-16'),
      ('ate terca', '2026-11-12', '2026-11-17'),
      ('até quarta', '2026-11-12', '2026-11-18'),
      ('até quinta', '2026-11-12', '2026-11-19'),
      ('até sexta', '2026-11-12', '2026-11-13'),
      ('até sábado', '2026-11-12', '2026-11-14'),
      ('até domingo', '2026-11-12', '2026-11-15'),
      ('até amanhã', '2026-11-12', '2026-11-13'),
      ('ate amanha', '2026-11-12', '2026-11-13'),
      ('até dia 12', '2026-11-12', '2026-12-12'),
      ('até dia 20', '2026-11-12', '2026-11-20'),
      ('até 20 de novembro', '2026-11-12', '2026-11-20'),
      ('por 3 dias', '2026-11-12', '2026-11-15'),
      ('por uma semana', '2026-11-12', '2026-11-19'),
      ('por 2 semanas', '2026-11-12', '2026-11-26'),
      ('до понедельника', '2026-11-12', '2026-11-16'),
      ('до вторника', '2026-11-12', '2026-11-17'),
      ('до среды', '2026-11-12', '2026-11-18'),
      ('до четверга', '2026-11-12', '2026-11-19'),
      ('до пятницы', '2026-11-12', '2026-11-13'),
      ('до субботы', '2026-11-12', '2026-11-14'),
      ('до воскресенья', '2026-11-12', '2026-11-15'),
      ('до завтра', '2026-11-12', '2026-11-13'),
      ('до 20 ноября', '2026-11-12', '2026-11-20'),
      ('до 12', '2026-11-12', '2026-12-12'),
      ('на 1 день', '2026-11-12', '2026-11-13'),
      ('на 2 дня', '2026-11-12', '2026-11-14'),
      ('на 5 дней', '2026-11-12', '2026-11-17'),
      ('на неделю', '2026-11-12', '2026-11-19'),
      ('на 2 недели', '2026-11-12', '2026-11-26'),
      ('на 5 недель', '2026-11-12', '2026-12-17'),
      ('until 31 Feb', '2026-01-01', null),
      ('until I am done', '2026-11-12', null),
      ('до обеда', '2026-11-12', null),
      ('', '2026-11-12', null),
      ('prefixuntil Friday', '2026-11-12', null),
      ('until Fridayish', '2026-11-12', null),
      ('for 0 days', '2026-11-12', null),
      ('for 366 weeks', '2026-11-12', null),
      ('until Friday then for 2 days', '2026-11-12', '2026-11-13'),
      ('until 31 Feb then tomorrow', '2026-01-01', null),
      ('for the weekend', '2026-11-12', '2026-11-16'),
      ('fim de semana', '2026-11-16', '2026-11-23'),
      ('на выходные', '2026-11-15', '2026-11-16'),
      ('weekend until Friday', '2026-11-12', '2026-11-13'),
      ('weekend 20/11/2026', '2026-11-12', null),
      ('weekend until 31 Feb', '2026-01-01', null),
    ];
    for (final (phrase, date, expected) in cases) {
      expect(
        parseLoanDue(phrase, DateTime.parse(date)),
        expected,
        reason: phrase,
      );
    }
    expect(parseLoanDue('tomorrow', DateTime.utc(2026, 11, 12, 23)), isNull);
    expect(
      parseLoanDue('by tomorrow', DateTime.utc(2026, 11, 12, 23)),
      '2026-11-13',
    );
  });
}
